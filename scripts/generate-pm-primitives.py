"""Generate periodic first/second primitives of the oscillator cubic tables.

Requires NumPy. Run on Linux (extended precision longdouble prefix sums).
The committed little-endian f64 coefficients are embedded in the plugin.
"""
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent / "src/oscillator"
BANDS = np.unique(np.floor(2 ** (np.arange(29) / 2)).astype(int))


def generate():
    first, second, records = bytearray(), bytearray(), []
    for wave in ["sine", "triangle", "square", "saw"]:
        rows = []
        for harmonic in ([1] if wave == "sine" else BANDS):
            length = (max(4096, 8 * int(harmonic)) + 3) // 4 * 4
            k = np.arange(1, harmonic + 1)
            if wave == "sine":
                amplitude = np.ones(1)
            elif wave == "saw":
                amplitude = -2 / (np.pi * k)
            elif wave == "square":
                amplitude = np.where(k % 2, 4 / (np.pi * k), 0.)
            else:
                amplitude = np.where(k % 2, 8 * np.where(k % 4 == 1, 1., -1.) / (np.pi * k)**2, 0.)
            spectrum = np.zeros(length // 2 + 1, complex)
            spectrum[1:harmonic + 1] = -1j * amplitude * length / 2
            values = np.fft.irfft(spectrum, length)
            if wave != "sine":
                values = values.astype("f4").astype("f8")
            a, b, c, d = np.roll(values, 1), values, np.roll(values, -1), np.roll(values, -2)
            coefficients = np.column_stack([
                b, (-2*a - 3*b + 6*c - d)/6, (a - 2*b + c)/2, (-a + 3*b - 3*c + d)/6,
            ])
            if wave != "sine":
                coefficients = coefficients.astype("f4").astype("f8")
            # Integrate the same piecewise cubic twice. Remove the integration
            # constant's mean at each order so both primitives remain periodic.
            coefficients = coefficients.astype(np.longdouble)
            step = np.longdouble(1) / length
            dc = (coefficients / np.arange(1, 5)).sum() / length
            coefficients[:, 0] -= dc
            area = (coefficients / np.arange(1, 5)).sum(axis=1) * step
            prefix = np.r_[np.longdouble(0), np.cumsum(area)[:-1]]
            c1 = np.column_stack([prefix, coefficients * step / np.arange(1, 5)])
            c1[:, 0] -= (c1 / np.arange(1, 6)).sum() / length
            area = (c1 / np.arange(1, 6)).sum(axis=1) * step
            prefix = np.r_[np.longdouble(0), np.cumsum(area)[:-1]]
            c2 = np.column_stack([prefix, c1 * step / np.arange(1, 6)])
            c2[:, 0] -= (c2 / np.arange(1, 7)).sum() / length
            rows.append(f"    Table {{ n: {length}.0, h: {int(harmonic)}.0, "
                        f"a: {len(first)//8}, b: {len(second)//8} }},")
            first.extend(c1.astype("<f8").tobytes())
            second.extend(c2.astype("<f8").tobytes())
        records.append(f"#[rustfmt::skip]\npub(super) static {wave.upper()}: [Table; {len(rows)}] = [\n"
                       + "\n".join(rows) + "\n];")
    (ROOT / "f1.bin").write_bytes(first)
    (ROOT / "f2.bin").write_bytes(second)
    (ROOT / "adaa_data.rs").write_text(
        "// Copyright (C) 2026 Yusuke Oda\n// SPDX-License-Identifier: AGPL-3.0-only\n"
        "// Generated by scripts/generate-pm-primitives.py. Do not edit.\n"
        "use super::Table;\n" + "\n".join(records) + "\n")
    print(len(first), len(second), "bytes")


if __name__ == "__main__":
    generate()
